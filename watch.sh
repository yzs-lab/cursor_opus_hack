#!/usr/bin/env bash
# Run by the LaunchAgent registered by install.sh. Synchronize the local extension and
# generated model schema with the current Cursor build.
set -uo pipefail

APP="${CURSOR_APP:-/Applications/Cursor.app}"
SRC="$APP/Contents/Resources/app/extensions/cursor-always-local"

override=""
for dir in "$HOME"/.cursor/extensions/anysphere.cursor-always-local-*; do
  if [ -f "$dir/node_modules/hook/dist/main.js" ]; then
    override="$dir"
  fi
done
[ -n "$override" ] || exit 0

# Wait for the application bundle before checking the installed files.
for _ in $(seq 30); do
  [ -d "$SRC/dist" ] && break
  sleep 1
done
[ -d "$SRC/dist" ] || exit 0

version=$(/usr/libexec/PlistBuddy -c 'Print :CFBundleShortVersionString' "$APP/Contents/Info.plist" 2>/dev/null)
schema="$override/node_modules/hook/dist/available-models.js"
if diff -rq "$SRC/dist" "$override/dist" >/dev/null 2>&1 &&
   [ -f "$schema" ] &&
   grep -Fqx "// Generated from Cursor $version; regenerated by install.sh after updates." "$schema"; then
  exit 0
fi

echo "$(date '+%F %T') Cursor $version 的内置扩展或模型 schema 已变化，重新安装"
if "$(dirname "$0")/install.sh"; then
  message="已为 Cursor $version 重新安装。如果 Cursor 已经打开，执行一次 Developer: Reload Window。"
else
  message="为 Cursor $version 重新安装失败，详见 ~/Library/Logs/cursor_opus_hack.log"
fi
osascript -e "display notification \"$message\" with title \"Cursor Opus Hack\"" >/dev/null 2>&1 || true

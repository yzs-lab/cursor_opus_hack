"use strict";

const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");

const RESPONSE_TYPE = "aiserver.v1.AvailableModelsResponse";

// Extract only generated protobuf constructors and their referenced types. Never load the
// workbench or extension host itself: either bundle has application startup side effects.
function extractResponseSchema(source) {
  const root = source.match(/([\w$]+)=([\w$]+)\.makeMessageType\("aiserver\.v1\.AvailableModelsResponse"/);
  if (!root) throw new Error("Cursor AvailableModelsResponse schema not found");
  const declarations = new Map();
  const escape = (value) => value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  function collect(symbol) {
    if (declarations.has(symbol)) return;
    const match = new RegExp(`(?<![\\w$])${escape(symbol)}=${escape(root[2])}\\.make(?:MessageType|Enum)\\(`).exec(source);
    if (!match) throw new Error(`Cursor schema dependency not found: ${symbol}`);
    const start = match.index;
    let depth = 1;
    let quote;
    let end = start + match[0].length;
    for (; end < source.length && depth > 0; end++) {
      const char = source[end];
      if (quote) {
        if (char === "\\") end++;
        else if (char === quote) quote = undefined;
      } else if (char === '"' || char === "'") quote = char;
      else if (char === "(") depth++;
      else if (char === ")") depth--;
    }
    if (depth !== 0) throw new Error(`Unterminated schema declaration: ${symbol}`);
    const declaration = source.slice(start, end);
    declarations.set(symbol, declaration);
    const references = declaration.matchAll(/\bT:([a-zA-Z_$][\w$]*)(?=[,}])|\.getEnumType\(([a-zA-Z_$][\w$]*)\)/g);
    for (const reference of references) collect(reference[1] || reference[2]);
  }
  collect(root[1]);
  return { runtime: root[2], root: root[1], declarations: [...declarations.values()] };
}

function loadResponseModule(content) {
  const context = { require, module: { exports: {} } };
  vm.runInNewContext(content, context, { timeout: 1000, filename: "available-models.js" });
  const Response = context.module.exports;
  if (Response.typeName !== RESPONSE_TYPE) throw new Error("Unexpected Cursor model response type");
  const sample = new Response({ models: [{ name: "schema-check" }], modelNames: ["schema-check"] });
  const decoded = Response.fromBinary(sample.toBinary());
  if (decoded.models[0]?.name !== "schema-check" || decoded.modelNames[0] !== "schema-check") {
    throw new Error("Cursor model schema failed its binary round-trip check");
  }
  return Response;
}

function generateResponseModule(appRoot) {
  // Read the AvailableModels schema from the renderer, with the extension host as an
  // additional source for supported Cursor builds.
  const candidates = [
    "out/vs/workbench/workbench.glass.main.js",
    "out/vs/workbench/workbench.desktop.main.js",
    "out/vs/workbench/api/node/extensionHostProcess.js",
  ];
  const errors = [];
  for (const filename of candidates) {
    try {
      const schema = extractResponseSchema(fs.readFileSync(path.join(appRoot, filename), "utf8"));
      const runtimePath = path.join(appRoot, "node_modules/@bufbuild/protobuf");
      const version = JSON.parse(fs.readFileSync(path.join(appRoot, "package.json"), "utf8")).version;
      const content = [
        '"use strict";',
        `// Generated from Cursor ${version}; regenerated by install.sh after updates.`,
        `const { proto3: ${schema.runtime} } = require(${JSON.stringify(runtimePath)});`,
        ...schema.declarations.map((declaration) => `var ${declaration};`),
        `module.exports = ${schema.root};`,
        "",
      ].join("\n");
      loadResponseModule(content);
      return content;
    } catch (error) {
      errors.push(`${filename}: ${error.message}`);
    }
  }
  throw new Error(`Cannot generate Cursor model schema; installation left unchanged:\n${errors.join("\n")}`);
}

module.exports = { extractResponseSchema, generateResponseModule, loadResponseModule };
